#!/usr/bin/env python3
"""codereview-ops: turn a findings JSON into a review report (Markdown, SARIF, GitHub annotations,
GitHub PR review payload) and an exit code for CI.

Findings JSON (written by the reviewer, see skills/review/references/findings-schema.md):
  {"summary": "...", "findings": [{"severity": "blocker|major|minor|nit", "category": "...",
    "file": "src/x.py", "line": 42, "end_line": 44, "title": "...", "detail": "...",
    "suggestion": "...", "confidence": "high|medium|low", "verified": true}],
   "strengths": ["..."], "checks_run": ["..."], "not_checked": ["..."]}

Usage:
  report.py FINDINGS.json [--manifest M] [--md OUT.md] [--sarif OUT.sarif] [--github-annotations]
            [--pr-review OUT.json] [--fail-on blocker|major|minor|nit|never]
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

SEVERITIES = ["blocker", "major", "minor", "nit"]
RANK = {s: i for i, s in enumerate(SEVERITIES)}
ICON = {"blocker": "🔴", "major": "🟠", "minor": "🟡", "nit": "⚪"}
SARIF_LEVEL = {"blocker": "error", "major": "error", "minor": "warning", "nit": "note"}
GH_LEVEL = {"blocker": "error", "major": "error", "minor": "warning", "nit": "notice"}


def validate(data: dict) -> list[str]:
    errs = []
    if not isinstance(data.get("findings"), list):
        return ["'findings' must be a list"]
    for i, f in enumerate(data["findings"]):
        for k in ("severity", "file", "title"):
            if not f.get(k):
                errs.append(f"finding {i}: missing '{k}'")
        if f.get("severity") and f["severity"] not in RANK:
            errs.append(f"finding {i}: severity '{f['severity']}' not in {SEVERITIES}")
        if f.get("line") is not None and not isinstance(f["line"], int):
            errs.append(f"finding {i}: 'line' must be an integer")
    return errs


def verdict(findings: list[dict]) -> str:
    sev = {f["severity"] for f in findings}
    if "blocker" in sev or "major" in sev:
        return "REQUEST CHANGES"
    if sev:
        return "APPROVE WITH NITS"
    return "APPROVE"


def loc(f: dict) -> str:
    if f.get("line"):
        end = f.get("end_line")
        return f"{f['file']}:{f['line']}" + (f"-{end}" if end and end != f["line"] else "")
    return f["file"]


def markdown(data: dict, findings: list[dict], manifest: dict | None, dropped: int) -> str:
    v = verdict(findings)
    counts = {s: sum(1 for f in findings if f["severity"] == s) for s in SEVERITIES}
    out = [f"# Code review — **{v}**", ""]
    if manifest:
        langs = ", ".join(manifest.get("languages", {}).keys()) or "-"
        t = manifest.get("totals", {})
        out.append(f"_Scope: {manifest.get('scope')} · {t.get('files', 0)} files · "
                   f"{t.get('changed_lines', 0)} changed lines · {langs}_")
        out.append("")
    out.append(" · ".join(f"{ICON[s]} {counts[s]} {s}" for s in SEVERITIES))
    out.append("")
    if data.get("summary"):
        out += [data["summary"].strip(), ""]
    if not findings:
        out += ["No issues found at or above the reporting threshold.", ""]
    for sev in SEVERITIES:
        group = [f for f in findings if f["severity"] == sev]
        if not group:
            continue
        out += [f"## {ICON[sev]} {sev.capitalize()} ({len(group)})", ""]
        for i, f in enumerate(group, 1):
            tag = f" `{f['category']}`" if f.get("category") else ""
            conf = f" · confidence: {f['confidence']}" if f.get("confidence") and f.get("confidence") != "high" else ""
            out.append(f"### {i}. {f['title']}")
            out.append(f"`{loc(f)}`{tag}{conf}")
            out.append("")
            if f.get("detail"):
                out += [f["detail"].strip(), ""]
            if f.get("suggestion"):
                sug = f["suggestion"].rstrip()
                if "\n" in sug and not sug.lstrip().startswith("```"):
                    sug = "```\n" + sug + "\n```"
                out += ["**Suggested fix:**", "", sug, ""]
    if data.get("strengths"):
        out += ["## What's good", ""] + [f"- {s}" for s in data["strengths"]] + [""]
    if data.get("checks_run"):
        out += ["## Evidence", ""] + [f"- {s}" for s in data["checks_run"]] + [""]
    if data.get("not_checked"):
        out += ["## Not checked", ""] + [f"- {s}" for s in data["not_checked"]] + [""]
    if dropped:
        out += [f"_{dropped} lower-severity finding(s) omitted by the reporting threshold/limit._", ""]
    out.append("<sub>Generated by codereview-ops</sub>")
    return "\n".join(out)


def sarif(findings: list[dict], root: str | None) -> dict:
    rules: dict[str, dict] = {}
    results = []
    for f in findings:
        rid = (f.get("category") or "general").lower().replace(" ", "-")
        rules.setdefault(rid, {"id": rid, "name": rid, "shortDescription": {"text": rid}})
        region = {}
        if f.get("line"):
            region = {"startLine": f["line"], "endLine": f.get("end_line") or f["line"]}
        msg = f["title"] + (("\n\n" + f["detail"]) if f.get("detail") else "") + \
            (("\n\nSuggested fix:\n" + f["suggestion"]) if f.get("suggestion") else "")
        results.append({
            "ruleId": rid, "level": SARIF_LEVEL[f["severity"]], "message": {"text": msg},
            "locations": [{"physicalLocation": {"artifactLocation": {"uri": f["file"], "uriBaseId": "SRCROOT"},
                                                **({"region": region} if region else {})}}],
            "properties": {"severity": f["severity"], "confidence": f.get("confidence", "high")},
        })
    run = {"tool": {"driver": {"name": "codereview-ops", "informationUri": "https://github.com/bosons14/codereview-ops",
                               "rules": list(rules.values())}}, "results": results}
    if root:
        run["originalUriBaseIds"] = {"SRCROOT": {"uri": Path(root).as_uri() + "/"}}
    return {"$schema": "https://json.schemastore.org/sarif-2.1.0.json", "version": "2.1.0", "runs": [run]}


def gh_escape(s: str) -> str:
    return s.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")


def pr_review_payload(data: dict, findings: list[dict], manifest: dict | None, body_md: str) -> dict:
    """Payload for POST /repos/{o}/{r}/pulls/{n}/reviews. Findings on lines outside the diff go in the body."""
    in_diff: dict[str, list[list[int]]] = {}
    if manifest and manifest.get("mode") == "diff":
        in_diff = {f["path"]: f["changed_ranges"] for f in manifest.get("files", [])}
    comments, leftovers = [], []
    for f in findings:
        rngs = in_diff.get(f["file"])
        line = f.get("line")
        if line and rngs and any(a <= line <= b for a, b in rngs):
            body = f"{ICON[f['severity']]} **{f['severity']}: {f['title']}**\n\n{f.get('detail', '').strip()}"
            if f.get("suggestion"):
                body += "\n\n**Suggested fix:**\n" + f["suggestion"].strip()
            c = {"path": f["file"], "line": f.get("end_line") or line, "side": "RIGHT", "body": body}
            if f.get("end_line") and f["end_line"] != line:
                c.update({"start_line": line, "start_side": "RIGHT"})
            comments.append(c)
        else:
            leftovers.append(f)
    v = verdict(findings)
    body = body_md if leftovers or not comments else \
        f"**codereview-ops: {v}**\n\n{(data.get('summary') or '').strip()}\n\n{len(comments)} inline comment(s)."
    return {"event": "COMMENT", "body": body, "comments": comments}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("findings")
    ap.add_argument("--manifest")
    ap.add_argument("--md", help="write Markdown report here (default: <workdir>/REVIEW.md)")
    ap.add_argument("--sarif", help="write SARIF 2.1.0 here")
    ap.add_argument("--github-annotations", action="store_true", help="print ::error/::warning workflow commands")
    ap.add_argument("--pr-review", help="write a GitHub PR review API payload here")
    ap.add_argument("--fail-on", choices=SEVERITIES + ["never"], help="exit 1 if any finding is at/above this")
    ap.add_argument("--min-severity", choices=SEVERITIES)
    ap.add_argument("--quiet", action="store_true", help="don't print the Markdown")
    args = ap.parse_args(argv)

    data = json.loads(Path(args.findings).read_text())
    errs = validate(data)
    if errs:
        print("invalid findings file:\n  " + "\n  ".join(errs), file=sys.stderr)
        return 2

    manifest = None
    mpath = Path(args.manifest) if args.manifest else None
    if mpath is None:
        gd = subprocess.run(["git", "rev-parse", "--absolute-git-dir"], capture_output=True, text=True).stdout.strip()
        cand = Path(gd) / "codereview-ops" / "manifest.json" if gd else None
        mpath = cand if cand and cand.is_file() else None
    if mpath and mpath.is_file():
        manifest = json.loads(mpath.read_text())
    cfg = (manifest or {}).get("config", {})
    min_sev = args.min_severity or cfg.get("min_severity", "nit")
    fail_on = args.fail_on or cfg.get("fail_on", "blocker")
    limit = int(cfg.get("max_findings", 60))

    # dedupe on (file, line, title) and sort by severity then location
    seen, uniq = set(), []
    for f in data["findings"]:
        key = (f["file"], f.get("line"), f["title"].strip().lower())
        if key not in seen:
            seen.add(key)
            uniq.append(f)
    uniq.sort(key=lambda f: (RANK[f["severity"]], f["file"], f.get("line") or 0))
    kept = [f for f in uniq if RANK[f["severity"]] <= RANK[min_sev]]
    blocking = [f for f in kept if f["severity"] in ("blocker", "major")]
    rest = [f for f in kept if f["severity"] not in ("blocker", "major")]
    kept = blocking + rest[: max(0, limit - len(blocking))]  # never drop blockers/majors for the limit
    dropped = len(uniq) - len(kept)

    md = markdown(data, kept, manifest, dropped)
    md_path = Path(args.md) if args.md else (Path(manifest["workdir"]) / "REVIEW.md" if manifest else None)
    if md_path:
        md_path.write_text(md)
    if args.sarif:
        Path(args.sarif).write_text(json.dumps(sarif(kept, (manifest or {}).get("root")), indent=2))
    if args.pr_review:
        Path(args.pr_review).write_text(json.dumps(pr_review_payload(data, kept, manifest, md), indent=2))
    if args.github_annotations:
        for f in kept:
            props = f"file={f['file']}" + (f",line={f['line']}" if f.get("line") else "") + \
                (f",endLine={f['end_line']}" if f.get("end_line") else "") + f",title={gh_escape(f['severity'] + ': ' + f['title'])}"
            print(f"::{GH_LEVEL[f['severity']]} {props}::{gh_escape(f.get('detail') or f['title'])}")
    if not args.quiet:
        print(md)
    if md_path:
        print(f"\nreport: {md_path}", file=sys.stderr)
    if fail_on != "never" and any(RANK[f["severity"]] <= RANK[fail_on] for f in kept):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
