def test_uncommitted_changes_and_untracked(repo):
    (repo / "src/a.py").write_text("def f(x):\n    return x + 1\n")
    (repo / "src/new.go").write_text("package x\n")
    m = run_collect(repo)
    paths = {f["path"]: f for f in m["files"]}
    assert m["scope"] == "uncommitted changes vs HEAD"
    assert paths["src/a.py"]["changed_ranges"] == [[2, 2]]
    assert paths["src/new.go"]["status"] == "A" and paths["src/new.go"]["language"] == "Go"
    assert m["signals"]["source_changed_without_tests"] is True


def test_branch_vs_base_and_ignores_lockfile(repo):
    sh("git checkout -qb feat", repo)
    (repo / "package-lock.json").write_text('{"a":1}\n')
    (repo / "run.sh").write_text("echo hi\nrm -rf $DIR/\n")
    sh("git commit -qam change", repo)
    m = run_collect(repo)
    assert m["base"] == "main"
    assert [f["path"] for f in m["files"]] == ["run.sh"]
    assert any(s["path"] == "package-lock.json" for s in m["skipped"])
    assert m["files"][0]["language"] == "Shell"


def test_last_commit_when_clean(repo):
    (repo / "src/a.py").write_text("import pickle\ndef f(x):\n    return pickle.loads(x)\n")
    sh("git commit -qam c2", repo)
    m = run_collect(repo)
    assert m["scope"].startswith("last commit")
    assert "deserialize" in m["files"][0]["risk_tags"]


def test_staged_only(repo):
    (repo / "src/a.py").write_text("x = 1\n")
    (repo / "run.sh").write_text("echo changed\n")
    sh("git add src/a.py", repo)
    m = run_collect(repo, "--staged")
    assert [f["path"] for f in m["files"]] == ["src/a.py"]


def test_paths_full_file_and_generated_skip(repo):
    (repo / "src/gen.py").write_text("# Code generated by tool. DO NOT EDIT.\nx = 1\n")
    m = run_collect(repo, "--paths", str(repo / "src"))
    paths = [f["path"] for f in m["files"]]
    assert paths == ["src/a.py"]
    assert m["files"][0]["changed_ranges"] == [[1, 2]]
    assert any(s["reason"] == "generated" for s in m["skipped"])


def test_diff_file_mode(repo, tmp_path_factory):
    patch = ("diff --git a/lib/x.rs b/lib/x.rs\nnew file mode 100644\n--- /dev/null\n+++ b/lib/x.rs\n"
             "@@ -0,0 +1,2 @@\n+fn main() {}\n+let k = \"AKIAIOSFODNN7EXAMPLE\";\n")
    pf = tmp_path_factory.mktemp("p") / "pr.patch"
    pf.write_text(patch)
    m = run_collect(repo, "--diff-file", str(pf))
    assert m["files"][0]["language"] == "Rust" and m["files"][0]["on_disk"] is False
    assert m["secrets"] and m["secrets"][0]["line"] == 2


