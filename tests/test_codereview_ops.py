def sh(cmd, cwd):
    subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, shell=isinstance(cmd, str))


@pytest.fixture()
def repo(tmp_path):
    sh("git init -q -b main && git config user.email t@t && git config user.name t", tmp_path)
    (tmp_path / "src").mkdir()
    (tmp_path / "src/a.py").write_text("def f(x):\n    return x\n")
    (tmp_path / "run.sh").write_text("echo hi\n")
    (tmp_path / "package-lock.json").write_text("{}\n")
    sh("git add -A && git commit -qm init", tmp_path)
    return tmp_path


def run_collect(repo, *args):
    rc = collect.main(["--root", str(repo), "--json", *args])
    assert rc == 0
    return json.loads((repo / ".git/codereview-ops/manifest.json").read_text())


