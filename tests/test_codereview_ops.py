# ---------------------------------------------------------------- secrets

def test_secrets_detected_and_masked():
    text = 'AWS = "AKIAIOSFODNN7EXAMPLE"\ntoken = "ghp_' + "a" * 36 + '"\npassword = "Xk9#mQ2vLp8zR4tY"\n'
    hits = scan_text(text, "f")
    rules = {h["rule"] for h in hits}
    assert {"aws-access-key", "github-token", "hardcoded-credential"} <= rules
    assert all("EXAMPLE" not in h["match"] for h in hits)


def test_secret_placeholders_and_allow_comment_ignored():
    text = ('password = "changeme"\napi_key = "${API_KEY}"\n'
            'secret = "Xk9#mQ2vLp8zR4tY"  # codereview-ops: allow-secret\n')
    assert scan_text(text, "f") == []


def test_anthropic_key_not_double_reported():
    hits = scan_text('k = "sk-ant-api03-' + "x1Y2" * 8 + '"', "f")
    assert [h["rule"] for h in hits] == ["anthropic-key"]


