# ---------------------------------------------------------------- report

def findings(*sevs):
    return {"summary": "s", "findings": [
        {"severity": s, "category": "correctness", "file": "a.py", "line": i + 1, "title": f"t{i}"}
        for i, s in enumerate(sevs)]}


def test_report_verdicts():
    assert report.verdict([]) == "APPROVE"
    assert report.verdict(findings("nit")["findings"]) == "APPROVE WITH NITS"
    assert report.verdict(findings("minor", "major")["findings"]) == "REQUEST CHANGES"


def test_report_validation():
    assert report.validate({"findings": [{"severity": "huge", "file": "a", "title": "t"}]})
    assert report.validate({"findings": [{"severity": "nit"}]})
    assert not report.validate(findings("blocker"))


def test_report_cli_exit_and_outputs(tmp_path):
    f = tmp_path / "f.json"
    f.write_text(json.dumps(findings("major", "nit", "nit")))
    sarif = tmp_path / "o.sarif"
    md = tmp_path / "r.md"
    rc = report.main([str(f), "--manifest", str(tmp_path / "none.json"), "--md", str(md), "--sarif", str(sarif),
                      "--fail-on", "major", "--quiet"])
    assert rc == 1
    s = json.loads(sarif.read_text())
    assert s["version"] == "2.1.0" and len(s["runs"][0]["results"]) == 3
    assert "REQUEST CHANGES" in md.read_text()
    assert report.main([str(f), "--manifest", str(tmp_path / "none.json"), "--md", str(md),
                        "--fail-on", "blocker", "--quiet"]) == 0


def test_pr_payload_inline_only_in_diff():
    manifest = {"mode": "diff", "files": [{"path": "a.py", "changed_ranges": [[1, 1]]}]}
    data = findings("major", "minor")
    p = report.pr_review_payload(data, data["findings"], manifest, "BODY")
    assert [c["line"] for c in p["comments"]] == [1]
    assert p["event"] == "COMMENT" and p["body"] == "BODY"


# ---------------------------------------------------------------- hook

def test_secret_guard_hook(tmp_path):
    hook = ROOT / "hooks/scripts/secret_guard.py"
    bad = tmp_path / "cfg.yaml"
    bad.write_text("token: ghp_" + "b" * 36 + "\n")
    good = tmp_path / "ok.py"
    good.write_text("x = 1\n")
    for path, code in ((bad, 2), (good, 0)):
        p = subprocess.run([sys.executable, str(hook)], input=json.dumps({"tool_input": {"file_path": str(path)}}),
                           capture_output=True, text=True)
        assert p.returncode == code
    assert "ghp_" + "b" * 36 not in p.stderr
