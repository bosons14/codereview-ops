def test_config_and_rules_files(repo):
    (repo / ".codereview-ops.json").write_text(json.dumps({"ignore": ["run.sh"], "fail_on": "major"}))
    (repo / "CODEREVIEW.md").write_text("- no raw SQL\n")
    (repo / "run.sh").write_text("echo 2\n")
    m = run_collect(repo, "--paths", str(repo / "run.sh"))
    assert m["files"] == [] and m["config"]["fail_on"] == "major"
    assert "CODEREVIEW.md" in m["rule_files"]


def test_batching(repo):
    cfg = {"batch_lines": 10, "batch_files": 2}
    (repo / ".codereview-ops.json").write_text(json.dumps(cfg))
    for i in range(5):
        (repo / f"src/m{i}.py").write_text("x = 1\n" * 6)
    m = run_collect(repo)
    assert sum(len(b["files"]) for b in m["batches"]) == len(m["files"])
    assert all(len(b["files"]) <= 2 for b in m["batches"])


